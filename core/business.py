def diagnose(raw: Any) -> dict:
    profile = validate_profile(raw)
    if "error" in profile:
        return profile
    language = profile["locale"]
    playbook = PLAYBOOKS[language][profile["industry"]]
    order = [profile["goal"]] + [key for key in GOALS[language] if key != profile["goal"]]
    question_order = list(QUESTIONS[language])
    selected = ai.prioritize_business_actions({
        "profile": profile,
        "available_actions": {key: {"title": row[0], "description": row[1]} for key, row in playbook.items()},
        "available_questions": QUESTIONS[language],
    })
    source = "fallback"
    if selected:
        action_ids = selected.get("action_ids", [])
        question_ids = selected.get("question_ids", [])
        if (len(action_ids) == 3 and set(action_ids) == set(order)
                and 3 <= len(question_ids) <= 5 and len(set(question_ids)) == len(question_ids)
                and all(key in QUESTIONS[language] for key in question_ids)):
            order, question_order, source = action_ids, question_ids, "openai"
    opportunities = []
    for key in order:
        title, description, metric, first_step = playbook[key]
        opportunities.append({
            "title": title, "description": description, "metric": metric, "kpi": metric,
            "first_step": first_step,
            "effort": "Небольшой пилот; объём работ уточняется" if language == "ru" else "Шағын пилот; жұмыс көлемі нақтыланады",
        })
    goal = GOALS[language][profile["goal"]]
    if language == "kk":
        summary = (f"{profile['business_name']} · {profile['city']}. Сіз таңдаған мақсат: {goal}. "
                   f"Алдымен «{opportunities[0]['title']}» гипотезасын тексеруді ұсынамыз. "
                   "Төменде төрт апталық пилоттың ұсынысы берілген; мерзімді кәсіпкер бекітеді. "
                   "Нақты табыс пен үнем бастапқы дерек пен өлшеусіз белгісіз.")
        task_draft = (f"Бизнес: {profile['business_name']}\nҚала/аудан: {profile['city']}\n"
                      f"Мақсат: {goal}\nКәсіпкер сипаттаған жағдай:\n{profile['challenge']}")
    else:
        summary = (f"{profile['business_name']} · {profile['city']}. Ваша цель: {goal}. "
                   f"Предлагаем сначала проверить гипотезу «{opportunities[0]['title']}». "
                   "Ниже — предложенный пилот на четыре недели; сроки подтверждает владелец. "
                   "Фактическая прибыль и экономия неизвестны до получения исходных данных и замеров.")
        task_draft = (f"Бизнес: {profile['business_name']}\nГород/район: {profile['city']}\n"
                      f"Цель: {goal}\nСитуация со слов владельца:\n{profile['challenge']}")
    # The existing task builder accepts 4,000 characters. Preserve the complete
    # supplied situation rather than silently cutting it to fit added labels.
    if len(task_draft) > ai.MAX_DRAFT_LENGTH:
        task_draft = profile["challenge"]
    return deepcopy({
        "source": source, "summary": summary, "opportunities": opportunities,
        "plan": _pilot_plan(opportunities[0], language),
        "questions": [QUESTIONS[language][key] for key in question_order],
        "task_draft": task_draft,
    })
