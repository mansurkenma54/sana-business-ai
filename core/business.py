def validate_profile(raw: Any) -> dict:
    """Return normalized profile or an explicit input error, without side effects."""
    def invalid(message: str) -> dict:
        return {"error": {"code": "invalid_input", "message": message}}

    if not isinstance(raw, dict):
        return invalid("Ожидался JSON-объект.")
    language = raw.get("locale", "ru")
    if not isinstance(language, str) or language not in GOALS:
        return invalid("Язык должен быть ru или kk.")
    profile = {"locale": language}
    limits = {"business_name": (2, 160), "city": (1, 120), "challenge": (20, 4000)}
    for key, (minimum, maximum) in limits.items():
        value = raw.get(key)
        if not isinstance(value, str) or not minimum <= len(value.strip()) <= maximum:
            message = f"Поле «{key}»: требуется текст от {minimum} до {maximum} символов."
            if language == "kk":
                message = f"«{key}» өрісіне {minimum}–{maximum} таңбалы мәтін енгізіңіз."
            return invalid(message)
        if any(ord(char) < 32 and char not in "\n\r\t" for char in value):
            return invalid("Текст содержит недопустимые управляющие символы.")
        profile[key] = value.strip()
    for key, allowed in (("industry", INDUSTRIES), ("goal", GOALS[language])):
        value = raw.get(key)
        if not isinstance(value, str) or value not in allowed:
            return invalid(f"Выберите допустимое значение «{key}».")
        profile[key] = value
    return profile


def templates(language: str = "ru") -> dict:
    if language not in GOALS:
        return {"error": {"code": "invalid_input", "message": "Язык должен быть ru или kk."}}
    rows = []
    for industry in INDUSTRIES:
        title, problem = TEMPLATE_META[language][industry]
        actions = PLAYBOOKS[language][industry]
        rows.append({
            "id": industry, "industry": industry, "title": title,
            "problem": problem, "description": actions["revenue"][1],
            "kpi": actions["revenue"][2],
            "steps": [actions[key][3] for key in ("revenue", "costs", "time")],
        })
    return {"templates": rows}


